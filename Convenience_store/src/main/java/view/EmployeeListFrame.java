    public void LoadEmpTableData() {
        DefaultTableModel EmpTableModel = new DefaultTableModel(){
            //Khóa sửa trực tiếp trong cell 
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        EmployeeTable1.setModel(EmpTableModel);//Gán model cho table
        EmpTableModel.setColumnIdentifiers(new Object[]{"Id", "Họ Và Tên", "Ngày Tháng Năm Sinh", "Giới tính", "Số CMND", "Barcode", "Số Điện Thoại", "Email", "Địa Chỉ", "Làm Tại", "Lương Theo Giờ","Trạng Thái","Store_id"});
        EmpTableModel.setRowCount(0);
        try {
            List<Employee> EmpList = empSvc.getAllEmployees();
            // Thay thế store name thay vì store id
            StoreRepository storeRepo = new StoreRepository();
            List<Store> storeList = storeRepo.findAll();
            for (Employee employee : EmpList) {
                String storeName = storeList.stream()
                        .filter(store -> store.getId() == employee.getStoreId())
                        .findFirst()
                        .map(Store::getStoreName)
                        .orElse("Không xác định");
                EmpTableModel.addRow(new Object[]{employee.getId(), employee.getFullName(), employee.getBirthday(), employee.getGender(), employee.getIdCard(), employee.getEmployeeBarcode(), employee.getPhone(), employee.getEmail(), employee.getAddress(), storeName, employee.getHourlyRate(), employee.getStatus(), employee.getStoreId()});
            }
            // Ẩn cột id
            EmployeeTable1.getColumnModel().getColumn(12).setWidth(0);
            EmployeeTable1.getColumnModel().getColumn(12).setMaxWidth(0);
            EmployeeTable1.getColumnModel().getColumn(12).setMinWidth(0);
            EmployeeTable1.getColumnModel().getColumn(12).setPreferredWidth(0);
            EmployeeTable1.getColumnModel().getColumn(12).setResizable(false);
            EmployeeTable1.getColumnModel().getColumn(12).setResizable(false);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(rootPane, "Lỗi khi tải dữ liệu nhân viên", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }

    }

