    private void EditEmpBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_EditEmpBtnMouseClicked
        int selectedrow = EmployeeTable1.getSelectedRow();
        if(selectedrow != -1){
            int id = (int) EmployeeTable1.getValueAt(selectedrow, 0);
            String fullName = (String) EmployeeTable1.getValueAt(selectedrow, 1);
            Date birthday = (Date) EmployeeTable1.getValueAt(selectedrow, 2);
            String gender = (String) EmployeeTable1.getValueAt(selectedrow, 3);
            String idCard = (String) EmployeeTable1.getValueAt(selectedrow, 4);
            String employeeBarcode = (String) EmployeeTable1.getValueAt(selectedrow, 5);
            String phone = (String) EmployeeTable1.getValueAt(selectedrow, 6);
            String email = (String) EmployeeTable1.getValueAt(selectedrow, 7);
            String address = (String) EmployeeTable1.getValueAt(selectedrow, 8);
            //Cast về store_id trước khi truyền 
            //Lấy store_id từ cột 12
            int storeId = (int) EmployeeTable1.getValueAt(selectedrow, 12);
            BigDecimal hourlyRate = (BigDecimal) EmployeeTable1.getValueAt(selectedrow, 10);
            String status = (String) EmployeeTable1.getValueAt(selectedrow, 11);
            Employee emp = new Employee(id, fullName, birthday, gender, idCard, employeeBarcode, phone, email, address, storeId, hourlyRate, status, null, null, false, null);
            AddEmpDialog updateEmp =  new AddEmpDialog(this, true, emp);
            updateEmp.setVisible(true);
            LoadEmpTableData();
        }else{
            JOptionPane.showMessageDialog(rootPane, "Vui lòng chọn 1 hàng");
        }
    }//GEN-LAST:event_EditEmpBtnMouseClicked

